#Задание
#Найдите сумму всех четных чисел от 0 до n включительно.
#Формат входных данных
#Дано целое положительно число.
#Формат выходных данных
#Вывести одно число, требуемое по условию задачи.
n = int(input())
summa = 0
for i in range(n +1):
    if i % 2 == 0:
        summa = summa + i
print(summa)
#Задание
#Даны два целые числа a и b.
#Выведите на экран все целые четные числа от a до b включительно.
#Формат входных данных
#Даны два целые числа, каждое на отдельной строке. Гарантируется, что a < b.
#Формат выходных данных
#Выведите все числа, требуемые по условию задачи, каждое на отдельной строке.
a = int(input())
b = int(input())
for i in range(a, b + 1):
    if i % 2 == 0:
        print(i)